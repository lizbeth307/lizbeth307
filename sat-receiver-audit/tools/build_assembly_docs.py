class Model:
    def __init__(self, base=BASE):
        self.base = base
        self.components = []
        for path in sorted((base / "design").glob("E[1-5].json")):
            graph = json.loads(path.read_text(encoding="utf-8"))
            for comp in graph["components"]:
                self.components.append(dict(comp, _sheet=graph["sheet"]))
        self.by_ref = {c["ref"]: c for c in self.components}
        self.open_items = {}
        for path in sorted((base / "design").glob("E[1-5].json")):
            for item in json.loads(path.read_text(encoding="utf-8")).get("open_items", []):
                self.open_items[item["id"]] = item
        with (base / "pcb/generated/components.csv").open(encoding="utf-8", newline="") as f:
            self.partition = {row["ref"]: row for row in csv.DictReader(f)}
        db = json.loads((base / "design/parts/parts.json").read_text(encoding="utf-8"))
        self.families = {fam["id"]: {size["pins"]: size for size in fam["sizes"]} for fam in db.get("harness_families", [])}
        self.family_terminal = {fam["id"]: fam.get("terminal") for fam in db.get("harness_families", [])}
        self.db_part = {r: part for part in db["parts"] for r in part["refs"]}
        self.unit_info = OrderedDict((u[0], {"kind": u[1], "name": u[2], "place": u[3]}) for u in D.UNITS)
        self.allocate()
        self.collect_nets()

    def allocate(self):
        self.unit_of, missing = {}, []
        for comp in self.components:
            ref = comp["ref"]
            unit = D.UNIT_OF_REF.get(ref) or D.UNIT_OF_GROUP.get((comp["_sheet"], comp.get("group", "")))
            if not unit:
                row = self.partition.get(ref, {})
                board = D.BOARD_OF_DOMAIN.get(row.get("board_candidate", ""))
                if board:
                    unit = board
                elif ref.startswith(D.RF_DOMAIN_PREFIXES):
                    unit = ref
                    self.unit_info.setdefault(ref, {"kind": "rf", "name": f"{ref} {comp['value']}", "place": "РЧ-тракт"})
            if not unit:
                missing.append(ref)
            elif unit not in self.unit_info:
                fail(f"{ref} is allocated to unknown unit {unit}")
            else:
                self.unit_of[ref] = unit
        if missing:
            fail("components without a physical place (add to tools/assembly_data.py): " + ", ".join(sorted(missing, key=ref_key)))
        self.order = {u: i for i, u in enumerate(self.unit_info)}
        # Places that contradict the board partition of components.csv must be acknowledged with a reason.
        self.deviations, unacked = [], []
        for comp in sorted(self.components, key=lambda c: ref_key(c["ref"])):
            ref = comp["ref"]
            candidate = self.partition.get(ref, {}).get("board_candidate", "")
            board = D.BOARD_OF_DOMAIN.get(candidate)
            if board and self.unit_of[ref] != board:
                self.deviations.append((ref, comp["_sheet"], candidate, board, self.unit_of[ref]))
                if not D.partition_deviation(ref, self.unit_of[ref]):
                    unacked.append(f"{ref} ({candidate} → {self.unit_of[ref]})")
        if unacked:
            fail("places that differ from pcb/generated/components.csv without a reason in PARTITION_DEVIATIONS: " + ", ".join(unacked))

    def collect_nets(self):
        self.nets = defaultdict(lambda: defaultdict(list))
        for comp in self.components:
            for pin in comp["pins"]:
                if pin.get("net"):
                    self.nets[pin["net"]][self.unit_of[comp["ref"]]].append((comp["ref"], str(pin["number"]), pin.get("type", ""), pin.get("name", "")))

    def is_board(self, unit):
        return self.unit_info[unit]["kind"] == "board"

    def is_rf(self, unit):
        return self.unit_info[unit]["kind"] == "rf"


def classify(model):
    """Split cross-unit nets into routed wires, factory assemblies, RF coax and the chassis bond."""
    routed, assemblies, coax = {}, defaultdict(list), {}
    patterns = [(a[0], re.compile(a[2])) for a in D.ASSEMBLIES]
    for net in sorted(model.nets):
        units = model.nets[net]
        if len(units) < 2 or net in ("GND", "CHASSIS"):
            continue
        hit = [aid for aid, rx in patterns if rx.search(net)]
        if len(hit) > 1:
            fail(f"net {net} matches several assemblies {hit}")
        if hit:
            assemblies[hit[0]].append(net)
        elif net.startswith("E4_") or net == "GNSS_ANT":
            coax[net] = units
        else:
            routed[net] = units
    for aid, _ in patterns:
        if not assemblies.get(aid):
            fail(f"assembly {aid} carries no cross-unit net")
    return routed, assemblies, coax


def route(model, routed):
    """Each net: shortest paths over harness segments; boards may carry a net through."""
    seg_by_id = {s[0]: s for s in D.SEGMENTS}
    adj = defaultdict(list)
    for seg in D.SEGMENTS:
        adj[seg[1]].append((seg[2], seg[0]))
        adj[seg[2]].append((seg[1], seg[0]))
    for a, b in D.INTERNAL_LINKS:
        adj[a].append((b, None))
        adj[b].append((a, None))
    for unit in seg_by_id.values():
        for end in unit[1:3]:
            if end not in model.unit_info:
                fail(f"segment {unit[0]} names unknown unit {end}")
    seg_nets, passthrough, internal = defaultdict(list), defaultdict(set), defaultdict(set)
    for net, units in routed.items():
        wanted = sorted(units, key=model.order.get)
        def is_driver(u):
            return any(p[2] in ("power_out", "output") for p in units[u])
        root = next((u for u in wanted if is_driver(u)), wanted[0])
        tree, edges = {root}, []
        for target in wanted:
            if target in tree:
                continue
            prev, queue = {u: None for u in tree}, list(sorted(tree, key=model.order.get))
            while queue and target not in prev:
                nxt = []
                for node in queue:
                    for other, seg in adj[node]:
                        if other in prev:
                            continue
                        if seg is None and not (node in units and other in units):
                            continue
                        if seg is not None and other not in units and not model.is_board(other):
                            continue
                        if seg is not None and seg in D.SEGMENT_NETS and net not in D.SEGMENT_NETS[seg]:
                            continue
                        prev[other] = (node, seg)
                        nxt.append(other)
                queue = nxt
            if target not in prev:
                fail(f"net {net}: no harness path to {target} (units {wanted})")
            node = target
            while prev[node] is not None:
                parent, seg = prev[node]
                edges.append((parent, node, seg))
                tree.add(node)
                node = parent
        for parent, node, seg in edges:
            if seg is None:
                internal[net].add((parent, node))
            elif net not in seg_nets[seg]:
                seg_nets[seg].append(net)
            for u in (parent, node):
                if u not in units:
                    passthrough[u].add(net)
    unused = [s[0] for s in D.SEGMENTS if s[0] not in seg_nets]
    if unused:
        fail("segments that carry no net: " + ", ".join(unused))
    return seg_nets, passthrough, internal


def bundle_factor(n):
    if n <= 1:
        return 1.0
    return 0.5 if n >= 15 else (29 - n) / 28


def colour(net):
    for rx, name in D.COLOURS:
        if re.search(rx, net):
            return name
    return "білий"


ROUTES_JSON = "mechanical/generated/harness-routes.json"


def harness_routes(base=BASE):
    """Segment routes of the mechanical model (generated, committed): {segment: route} or {} when the file is absent."""
    path = Path(base) / ROUTES_JSON
    if not path.is_file():
        return {}
    return json.loads(path.read_text(encoding="utf-8")).get("segments", {})


def routed_length(text, route):
    """Length column of a segment: the model route length (MODEL ESTIMATE) replaces 'TBD (CAD)'; a limit text stays after it."""
    if not route or route.get("length_mm") is None or route.get("kind") == "external":
        return text
    label = f"{route['length_mm']} (модель{', кінець попередній' if route.get('provisional') else ''})"
    if route.get("kind") == "stock_lead":
        return f"{text}; траса {label}"
    if "TBD" in str(text):
        return label
    return f"{label}; {text}"


class Harness:
    def __init__(self, model):
        self.model = model
        self.routed, self.assemblies, self.coax = classify(model)
        self.seg_nets, self.passthrough, self.internal = route(model, self.routed)
        routes = harness_routes(model.base)
        self.segments = OrderedDict((s[0], s[:5] + (routed_length(s[5], routes.get(s[0])),) + s[6:]) for s in D.SEGMENTS)
        self.warnings = []
        self.wires, self.connectors = [], OrderedDict()
        for (sid, unit, net), text in D.END_PIN.items():
            ref, pin = text.split(" ")[0].split(".", 1)
            if not any(r == ref and p == pin for r, p, _, _ in model.nets[net].get(unit, [])):
                fail(f"END_PIN {sid} {unit} {net}: {ref}.{pin} is not on that net in that unit")
        for sid in self.segments:
            self.build_segment(sid)

    # end description for (segment, unit, net): explicit contacts or module pins
    def explicit_pins(self, sid, unit, net, family=None):
        pins = []
        for ref, pin, _, name in self.model.nets[net].get(unit, []):
            if sid not in EXPLICIT_SEGMENTS.get(ref, ()):
                continue
            if family and self.model.is_board(unit) and CONNECTOR_FAMILY.get(ref, "SOLDER") != family:
                continue  # a board-side connector of another family in the same segment
            pins.append((ref, pin, name))
        return sorted(pins, key=lambda p: (ref_key(p[0]), p[1]))

    def has_gnd(self, unit):
        return self.model.is_board(unit) or bool(self.model.nets["GND"].get(unit))

    def end_family(self, sid, unit, family_hint):
        seg = self.segments[sid]
        if seg[4] in ("IDC", "CABLE", "FAN3") and self.model.is_board(unit):
            return seg[4]
        if self.model.is_board(unit):
            # a soldered segment that lands on a graph connector of a board (S16 on J503 of the hatch board) takes that connector's family
            return (self.explicit_family(sid, unit) or family_hint) if family_hint == "SOLDER" else family_hint
        for ref in sorted(EXPLICIT_SEGMENTS, key=ref_key):
            if sid in EXPLICIT_SEGMENTS[ref] and self.model.unit_of.get(ref) == unit:
                return CONNECTOR_FAMILY.get(ref, "SOLDER")
        return "SOLDER" if seg[4] not in ("CABLE",) else "CABLE"

    def explicit_family(self, sid, unit):
        for ref in sorted(EXPLICIT_SEGMENTS, key=ref_key):
            if sid in EXPLICIT_SEGMENTS[ref] and self.model.unit_of.get(ref) == unit:
                return CONNECTOR_FAMILY.get(ref, "SOLDER")
        return None

    def current(self, sid, net):
        """Design current of a net in a segment; a segment behind a pass-through panel/cable part inherits the branch budget."""
        if (sid, net) in D.SEG_CURRENT:
            return D.SEG_CURRENT[(sid, net)], True
        seg = self.segments[sid]
        for unit in seg[1:3]:
            if self.model.is_board(unit):
                continue
            for other, oseg in self.segments.items():
                if other != sid and unit in oseg[1:3] and net in self.seg_nets[other] and (other, net) in D.SEG_CURRENT:
                    cont, prot, why, src = D.SEG_CURRENT[(other, net)]
                    return (cont, prot, why, f"та сама гілка, що {other}: {src}"), True
        if net in D.NET_CURRENT:
            return D.NET_CURRENT[net], True
        return SIGNAL, False

    def build_segment(self, sid):
        seg = self.segments[sid]
        a, b = seg[1], seg[2]
        override = seg[4]
        ph_limit = D.FAMILIES["PH"]["rating"] * D.FAMILIES["PH"]["share"]
        # item: [net, cont, prot, protection, source, k_min, family_hint, min_awg, declared, result]
        items = []
        for net in sorted(self.seg_nets[sid]):
            (cont, prot, why, src), declared = self.current(sid, net)
            k_min = max(1, len(self.explicit_pins(sid, a, net)), len(self.explicit_pins(sid, b, net)))
            hint = override or ("MF" if cont > ph_limit + 1e-9 or (prot or 0) > D.FAMILIES["PH"]["rating"] else "PH")
            min_awg = D.MIN_AWG.get(net)
            if not override and min_awg and min(D.FAMILIES[hint]["awg"]) > min_awg:
                hint = "MFJ"  # Micro-Fit 3.0 takes 20–24 AWG only
            items.append([net, cont, prot, why, src, k_min, hint, min_awg, declared])
        if any(i[6] == "MFJ" for i in items):
            for i in items:  # one power connector family per segment end
                if i[6] == "MF":
                    i[6] = "MFJ"
        if self.has_gnd(a) and self.has_gnd(b) and sid not in D.NO_GND:
            groups = [override] if override else [f for f in ("MFJ", "MF", "PH") if any(i[6] == f for i in items)]
            groups = [f for f in groups if (sid, f) not in D.GND_GROUP_SKIP]
            if not (self.model.is_board(a) and self.model.is_board(b)):
                groups = groups[:1]  # one return to a module or panel part
            for fam in groups:
                listed = [i for i in items if i[6] == fam and i[8]]
                if not listed and len(groups) == 1:
                    listed = [i for i in items if i[8]]
                cont = round(max([0.05] + [i[1] for i in listed]), 3)
                prot = max(((i[2] or i[1]) for i in listed), default=None)
                min_awg = min((i[7] for i in listed if i[7]), default=None)
                if sid in D.GND_CURRENT:
                    cont, prot = D.GND_CURRENT[sid]
                    min_awg = None
                k_min = max([1] + [len(self.explicit_pins(sid, end, "GND", fam)) for end in (a, b)])
                items.append(["GND", cont, prot, "повернення струму мереж цього роз'єму", "найбільший тривалий струм роз'єму", k_min, fam,
                              min_awg, cont > SIGNAL[0]])
        k = {id(i): i[5] for i in items}
        for _ in range(8):
            n = sum(k.values())
            changed = False
            for item in items:
                net, cont, prot, _, _, k_min, hint, min_awg, declared = item[:9]
                fam_a, fam_b = self.end_family(sid, a, hint), self.end_family(sid, b, hint)
                allowed = sorted(set(D.FAMILIES[fam_a]["awg"] if fam_a in D.FAMILIES else ANY_AWG)
                                 & set(D.FAMILIES[fam_b]["awg"] if fam_b in D.FAMILIES else ANY_AWG), reverse=True)
                if not allowed:
                    fail(f"{sid} {net}: no AWG common to {fam_a} and {fam_b}")
                fixed = D.FIXED_AWG.get((sid, net))
                if override in ("CABLE", "FAN3"):
                    fam_a = fam_b = override
                    allowed = list(D.FAMILIES[override]["awg"])
                if fixed and fixed not in allowed:
                    fail(f"{sid} {net}: fixed {fixed} AWG is outside {fam_a}/{fam_b}")
                if min_awg and override not in ("CABLE", "FAN3", "IDC"):
                    if fixed and fixed > min_awg:
                        fail(f"{sid} {net}: fixed {fixed} AWG is thinner than the {min_awg} AWG minimum")
                    allowed = [g for g in allowed if g <= min_awg]
                    if not allowed:
                        fail(f"{sid} {net}: {min_awg} AWG minimum is outside {fam_a}/{fam_b}")
                limits = [D.FAMILIES[f]["rating"] * D.FAMILIES[f]["share"] for f in (fam_a, fam_b)
                          if f in D.FAMILIES and D.FAMILIES[f]["rating"]]
                contact_limit = min(limits) if limits else None
                frozen = "IDC" in (fam_a, fam_b) or fixed or override in ("CABLE", "FAN3")
                if net != "GND" and not declared:
                    floor = max(D.FAMILIES[f]["signal_awg"] for f in (fam_a, fam_b) if f in D.FAMILIES)
                elif declared:
                    # a power wire in a rated family uses the gauge the contact rating is given for (JST: #24 only)
                    rated = [D.FAMILIES[f]["power_awg"] for f in (fam_a, fam_b) if f in D.FAMILIES and D.FAMILIES[f]["rating"]]
                    floor = min(rated) if rated else None
                else:
                    floor = None
                if floor and fixed and fixed > floor:
                    floor = fixed  # a gauge STACK names stays as named (reported in §11)
                item_k = k[id(item)]
                while True:
                    need_wire = (prot or cont) / item_k
                    awg = None
                    for g in ([fixed] if fixed else allowed):  # thinnest first
                        if floor and g > floor:
                            continue
                        if D.ESCC_IMAX.get(g, 0) * bundle_factor(n) >= need_wire:
                            awg = g
                            break
                    ok_contact = contact_limit is None or cont / item_k <= contact_limit + 1e-9
                    if (awg and ok_contact) or item_k >= 4 or frozen:
                        break
                    item_k += 1
                if item_k != k[id(item)]:
                    k[id(item)] = item_k
                    changed = True
                fallback = fixed or min([g for g in allowed if not floor or g <= floor] or allowed)
                item[9:] = [(fam_a, fam_b, awg or fallback, contact_limit, bool(awg), ok_contact)]
            if not changed:
                break
        n = sum(k.values())
        for item in items:
            fam_a, fam_b, awg, limit, ok_wire, ok_contact = item[9]
            net, cont, prot = item[:3]
            if not ok_wire:
                self.warnings.append(f"{sid} {net}: межа захисту {prot or cont:g} A більша за допустимий струм {k[id(item)]}×{awg} AWG "
                                     f"у сегменті з {n} провідників (ESCC 3901/001) — потрібна окрема межа струму на гілці")
            if not ok_contact:
                self.warnings.append(f"{sid} {net}: {cont:g} A на {k[id(item)]} контакт(и) перевищує проєктну межу {limit:.1f} A")
        counters, rows = defaultdict(int), []
        order = {"MFJ": 0, "MF": 1}
        for item in sorted(items, key=lambda i: (order.get(i[6], 2), 0 if i[0] == "GND" else 1, i[0])):
            net, cont, prot, why, src = item[:5]
            fam_a, fam_b, awg = item[9][:3]
            kk = k[id(item)]
            pa, pb = self.explicit_pins(sid, a, net, fam_a), self.explicit_pins(sid, b, net, fam_b)
            for pins, fam in ((pa, fam_a), (pb, fam_b)):
                if pins and kk > len(pins) and fam in ("MFJ", "MF", "PH", "IDC"):
                    self.warnings.append(f"{sid} {net}: потрібно {kk} провідники, а роз'єм має {len(pins)} контакт(и)")
            for idx in range(kk):
                mirror = (pa or pb)[idx % len(pa or pb)][1] if "IDC" in (fam_a, fam_b) and (pa or pb) else None
                # a graph connector on a board (J302 on CTRL) gets a dedicated mate on the other board, contact for contact
                mate_a = pb[idx % len(pb)][:2] if pb and not pa and not mirror and self.model.is_board(a) and self.model.is_board(b) else None
                mate_b = pa[idx % len(pa)][:2] if pa and not pb and not mirror and self.model.is_board(a) and self.model.is_board(b) else None
                end_a = self.end(sid, a, net, fam_a, pa, idx, counters, mirror, mate_a)
                end_b = self.end(sid, b, net, fam_b, pb, idx, counters, mirror, mate_b)
                rows.append((net, cont, prot, why, src, kk, idx, awg, end_a, end_b, fam_a, fam_b))
        for num, row in enumerate(rows, 1):
            net, cont, prot, why, src, kk, idx, awg, end_a, end_b, fam_a, fam_b = row
            wid = f"{sid}-{num:02d}"
            ohm = None if {"CABLE", "IDC"} & {fam_a, fam_b} else D.WIRE_OHM_PER_KM.get(awg)
            self.wires.append(OrderedDict([
                ("wire", wid), ("segment", sid), ("net", net), ("from_unit", a), ("from", end_a), ("to_unit", b), ("to", end_b),
                ("family_from", fam_a), ("family_to", fam_b), ("awg", awg), ("parallel", f"{idx + 1}/{kk}"),
                ("i_cont_a", f"{cont:g}"), ("i_prot_a", f"{prot:g}" if prot else ""), ("protection", why), ("current_source", src),
                ("bundle_n", n), ("colour", colour(net)), ("insulation", D.INSULATION), ("length_mm", self.segments[sid][5]),
                ("conductor_mohm_per_m", f"{ohm:g}" if ohm else "TBD"), ("marker", wid)]))

    def end(self, sid, unit, net, family, pins, idx, counters, mirror=None, mate=None):
        if pins:
            ref, pin, name = pins[idx % len(pins)]
            return f"{ref}.{pin}" + (f" ({name})" if name and name != pin else "")
        local = [f"{r}.{p}" for r, p, _, _ in self.model.nets[net].get(unit, [])]
        if self.model.is_board(unit):
            kind = {"MFJ": "J", "MF": "P", "PH": "S", "IDC": "I", "FAN3": "F"}.get(family, "C")
            limit = D.SIDE_ENTRY_PH_MAX if family == "PH" and unit in D.SIDE_ENTRY_UNITS else D.FAMILIES[family]["max_pins"]
            if mate:
                cid = f"X{sid[1:]}{kind}0-{unit}"  # index 0: mate of the graph connector at the other end
                pin = int(mate[1])
            else:
                key = (sid, unit, kind)
                counters[key] += 1
                pos = counters[key]
                cid = f"X{sid[1:]}{kind}{(pos - 1) // limit + 1}-{unit}"
                pin = int(mirror) if mirror else (pos - 1) % limit + 1
            conn = self.connectors.setdefault(cid, OrderedDict([("connector", cid), ("unit", unit), ("segment", sid), ("family", family),
                                                               ("pins", 0), ("nets", []), ("mate_of", mate[0] if mate else "")]))
            conn["pins"] = 40 if family == "IDC" else max(conn["pins"], pin, 2)  # PH and Micro-Fit start at 2 circuits
            if mate:
                conn["pins"] = max(conn["pins"], len(self.model.by_ref[mate[0]]["pins"]))  # the mate has every contact of its graph connector
            if family == "MFJ" and conn["pins"] % 2:
                conn["pins"] += 1  # Mini-Fit Jr. headers 5566/5569 are dual row
            conn["nets"].append(net)
            where = f" → {', '.join(local[:3])}{' …' if len(local) > 3 else ''}" if local else " (транзит)"
            return f"{cid}.{pin}{where}"
        if (sid, unit, net) in D.END_PIN:
            return "пайка: " + D.END_PIN[(sid, unit, net)]
        if not local:
            return "—"
        rest = f" (той самий вузол: {', '.join(local[1:3])})" if len(local) > 1 else ""
        return "пайка: " + local[0] + rest


def header_style(conn):
    return "header_side" if conn["family"] == "PH" and conn["unit"] in D.SIDE_ENTRY_UNITS else "header_top"


def db_item(model, fam, n, role):
    """MPN (+ LCSC) of a harness-family item from design/parts/parts.json, or a TBD text with the reason."""
    fid = D.FAMILIES[fam].get("db")
    if not fid:
        return f"TBD (немає в базі деталей: {D.FAMILIES[fam]['no_db']})"
    if role == "terminal":
        t = model.family_terminal.get(fid)
        return f"{t['mpn']} ({t['sku']['lcsc']})" if t else "—"
    size = model.families.get(fid, {}).get(n)
    if size is None:
        return f"TBD (немає в базі деталей: родина {fid} без розміру {n} конт.)"
    item = size.get(role)
    if item is None:
        why = size.get("note") or f"у базі немає ролі {role}"
        return f"TBD (немає в базі деталей: {why})"
    return f"{item['mpn']} ({item['sku']['lcsc']})"


def connector_parts(model, conn):
    fam, n = conn["family"], conn["pins"]
    fam_d = D.FAMILIES[fam]
    src = "design/parts/parts.json harness_families " + (fam_d.get("db") or "—") + ("; " + fam_d["source"] if fam_d.get("source") else "")
    if conn.get("mate_of"):
        part = model.db_part.get(conn["mate_of"], {})
        mate = next((e["mpn"] for e in part.get("extras", []) if "power-board end header" in e.get("item", "")), None)
        return (f"PHR-{n} — супутня деталь {conn['mate_of']} (база деталей)", f"{mate or 'TBD'} — супутня деталь {conn['mate_of']} (база деталей)",
                db_item(model, fam, n, "terminal"), "design/parts/parts.json " + part.get("id", "—"))
    header = db_item(model, fam, n, header_style(conn))
    if fam == "FAN3":
        return fam_d["housing"], header, "—", src
    terminal = db_item(model, fam, n, "terminal") if fam in CRIMP else "—"
    return db_item(model, fam, n, "housing"), header, terminal, src


