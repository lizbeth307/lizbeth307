class Model:
    def __init__(self, base=BASE):
        self.base = base
        self.components = []
        for path in sorted((base / "design").glob("E[1-5].json")):
            graph = json.loads(path.read_text(encoding="utf-8"))
            for comp in graph["components"]:
                self.components.append(dict(comp, _sheet=graph["sheet"]))
        self.by_ref = {c["ref"]: c for c in self.components}
        self.open_items = {}
        for path in sorted((base / "design").glob("E[1-5].json")):
            for item in json.loads(path.read_text(encoding="utf-8")).get("open_items", []):
                self.open_items[item["id"]] = item
        with (base / "pcb/generated/components.csv").open(encoding="utf-8", newline="") as f:
            self.partition = {row["ref"]: row for row in csv.DictReader(f)}
        db = json.loads((base / "design/parts/parts.json").read_text(encoding="utf-8"))
        self.families = {fam["id"]: {size["pins"]: size for size in fam["sizes"]} for fam in db.get("harness_families", [])}
        self.family_terminal = {fam["id"]: fam.get("terminal") for fam in db.get("harness_families", [])}
        self.db_part = {r: part for part in db["parts"] for r in part["refs"]}
        self.unit_info = OrderedDict((u[0], {"kind": u[1], "name": u[2], "place": u[3]}) for u in D.UNITS)
        self.allocate()
        self.collect_nets()

    def allocate(self):
        self.unit_of, missing = {}, []
        for comp in self.components:
            ref = comp["ref"]
            unit = D.UNIT_OF_REF.get(ref) or D.UNIT_OF_GROUP.get((comp["_sheet"], comp.get("group", "")))
            if not unit:
                row = self.partition.get(ref, {})
                board = D.BOARD_OF_DOMAIN.get(row.get("board_candidate", ""))
                if board:
                    unit = board
                elif ref.startswith(D.RF_DOMAIN_PREFIXES):
                    unit = ref
                    self.unit_info.setdefault(ref, {"kind": "rf", "name": f"{ref} {comp['value']}", "place": "РЧ-тракт"})
            if not unit:
                missing.append(ref)
            elif unit not in self.unit_info:
                fail(f"{ref} is allocated to unknown unit {unit}")
            else:
                self.unit_of[ref] = unit
        if missing:
            fail("components without a physical place (add to tools/assembly_data.py): " + ", ".join(sorted(missing, key=ref_key)))
        self.order = {u: i for i, u in enumerate(self.unit_info)}
        # Places that contradict the board partition of components.csv must be acknowledged with a reason.
        self.deviations, unacked = [], []
        for comp in sorted(self.components, key=lambda c: ref_key(c["ref"])):
            ref = comp["ref"]
            candidate = self.partition.get(ref, {}).get("board_candidate", "")
            board = D.BOARD_OF_DOMAIN.get(candidate)
            if board and self.unit_of[ref] != board:
                self.deviations.append((ref, comp["_sheet"], candidate, board, self.unit_of[ref]))
                if not D.partition_deviation(ref, self.unit_of[ref]):
                    unacked.append(f"{ref} ({candidate} → {self.unit_of[ref]})")
        if unacked:
            fail("places that differ from pcb/generated/components.csv without a reason in PARTITION_DEVIATIONS: " + ", ".join(unacked))

    def collect_nets(self):
        self.nets = defaultdict(lambda: defaultdict(list))
        for comp in self.components:
            for pin in comp["pins"]:
                if pin.get("net"):
                    self.nets[pin["net"]][self.unit_of[comp["ref"]]].append((comp["ref"], str(pin["number"]), pin.get("type", ""), pin.get("name", "")))

    def is_board(self, unit):
        return self.unit_info[unit]["kind"] == "board"

    def is_rf(self, unit):
        return self.unit_info[unit]["kind"] == "rf"


def classify(model):
    """Split cross-unit nets into routed wires, factory assemblies, RF coax and the chassis bond."""
    routed, assemblies, coax = {}, defaultdict(list), {}
    patterns = [(a[0], re.compile(a[2])) for a in D.ASSEMBLIES]
    for net in sorted(model.nets):
        units = model.nets[net]
        if len(units) < 2 or net in ("GND", "CHASSIS"):
            continue
        hit = [aid for aid, rx in patterns if rx.search(net)]
        if len(hit) > 1:
            fail(f"net {net} matches several assemblies {hit}")
        if hit:
            assemblies[hit[0]].append(net)
        elif net.startswith("E4_") or net == "GNSS_ANT":
            coax[net] = units
        else:
            routed[net] = units
    for aid, _ in patterns:
        if not assemblies.get(aid):
            fail(f"assembly {aid} carries no cross-unit net")
    return routed, assemblies, coax


def route(model, routed):
    """Each net: shortest paths over harness segments; boards may carry a net through."""
    seg_by_id = {s[0]: s for s in D.SEGMENTS}
    adj = defaultdict(list)
    for seg in D.SEGMENTS:
        adj[seg[1]].append((seg[2], seg[0]))
        adj[seg[2]].append((seg[1], seg[0]))
    for a, b in D.INTERNAL_LINKS:
        adj[a].append((b, None))
        adj[b].append((a, None))
    for unit in seg_by_id.values():
        for end in unit[1:3]:
            if end not in model.unit_info:
                fail(f"segment {unit[0]} names unknown unit {end}")
    seg_nets, passthrough, internal = defaultdict(list), defaultdict(set), defaultdict(set)
    for net, units in routed.items():
        wanted = sorted(units, key=model.order.get)
        def is_driver(u):
            return any(p[2] in ("power_out", "output") for p in units[u])
        root = next((u for u in wanted if is_driver(u)), wanted[0])
        tree, edges = {root}, []
        for target in wanted:
            if target in tree:
                continue
            prev, queue = {u: None for u in tree}, list(sorted(tree, key=model.order.get))
            while queue and target not in prev:
                nxt = []
                for node in queue:
                    for other, seg in adj[node]:
                        if other in prev:
                            continue
                        if seg is None and not (node in units and other in units):
                            continue
                        if seg is not None and other not in units and not model.is_board(other):
                            continue
                        if seg is not None and seg in D.SEGMENT_NETS and net not in D.SEGMENT_NETS[seg]:
                            continue
                        prev[other] = (node, seg)
                        nxt.append(other)
                queue = nxt
            if target not in prev:
                fail(f"net {net}: no harness path to {target} (units {wanted})")
            node = target
            while prev[node] is not None:
                parent, seg = prev[node]
                edges.append((parent, node, seg))
                tree.add(node)
                node = parent
        for parent, node, seg in edges:
            if seg is None:
                internal[net].add((parent, node))
            elif net not in seg_nets[seg]:
                seg_nets[seg].append(net)
            for u in (parent, node):
                if u not in units:
                    passthrough[u].add(net)
    unused = [s[0] for s in D.SEGMENTS if s[0] not in seg_nets]
    if unused:
        fail("segments that carry no net: " + ", ".join(unused))
    return seg_nets, passthrough, internal


def segment_wires(h, sid):
    """Wires of one segment; a branch (D.SEGMENT_BRANCHES) is listed under its parent bundle with ids <parent>-<branch>-nn."""
    if sid in D.SEGMENT_BRANCHES:
        return [w for w in h.wires if w["wire"].startswith(f"{D.SEGMENT_BRANCHES[sid]}-{sid}-")]
    return [w for w in h.wires if w["segment"] == sid and w["wire"].startswith(f"{sid}-") and w["wire"].count("-") == 1]


def bundle_factor(n):
    if n <= 1:
        return 1.0
    return 0.5 if n >= 15 else (29 - n) / 28


