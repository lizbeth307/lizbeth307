def board_rails(model, board):
    rails = []
    for net in sorted(model.nets):
        pins = model.nets[net].get(board, [])
        if net in ("GND",) or not pins:
            continue
        if net in D.NET_CURRENT or any(p[2] == "power_out" for p in pins):
            rails.append(net)
    return rails


