def md(value):
    return str(value).replace("|", "\\|").replace("\n", " ")


def blocks(text):
    """Blank line between Markdown blocks (heading, table, quote, list, paragraph) so every renderer agrees."""
    out, prev = [], ""
    for line in text.split("\n"):
        kind = ("h" if line.startswith("#") else "t" if line.startswith("|") else "q" if line.startswith(">")
                else "c" if line.startswith("<!--") else "l" if re.match(r"\d+\. |- ", line) else "p" if line.strip() else "")
        if out and kind and prev and (kind != prev or prev == "h"):
            if out[-1] != "":
                out.append("")
        out.append(line)
        prev = kind if line.strip() else ""
    return re.sub(r"\n{3,}", "\n\n", "\n".join(out)).strip("\n") + "\n"


def table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(md(c) for c in row) + " |" for row in rows]
    return "\n".join(out) + "\n"


def csv_text(header, rows):
    stream = io.StringIO(newline="")
    writer = csv.writer(stream, lineterminator="\n")
    writer.writerow(header)
    writer.writerows(rows)
    return stream.getvalue()


def ref_key(ref):
    m = re.fullmatch(r"([A-Z]+)(\d+)", ref)
    return (m[1], int(m[2])) if m else (ref, 0)


def source_text(key):
    if key in D.SOURCES:
        url, _ = D.SOURCES[key]
        return f"{key} ({url}, прочитано {D.READ_ON.get(key, D.READ)})"
    return key


