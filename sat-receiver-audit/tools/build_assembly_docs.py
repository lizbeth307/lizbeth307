def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="compare with the committed files, write nothing")
    args = ap.parse_args(argv)
    _, h, files = build_all()
    stale = []
    for rel, text in files.items():
        path = BASE / rel
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != text:
                stale.append(rel)
        else:
            path.write_text(text, encoding="utf-8", newline="\n")
    if stale:
        raise SystemExit("Assembly documents are stale; run python tools/build_assembly_docs.py: " + ", ".join(stale))
    print(f"assembly docs: {len(h.wires)} wires, {len(h.connectors)} harness connectors, {len(files)} files "
          + ("match" if args.check else "written"))
    return 0


