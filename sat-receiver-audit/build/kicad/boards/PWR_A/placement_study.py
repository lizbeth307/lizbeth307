#!/usr/bin/env python3
"""PWR-A placement study (W2 PCB-PWRA-1, B2B check W2 PCB-PWRA-2, two-sided SHRINK-2 and obstacle fix W2 PCB-PWRA-3):
the board_gen planner run on a PWR_A planner spec, standard library only.

  python3 build/kicad/boards/PWR_A/placement_study.py                  write the study of every spec in SPECS
  python3 build/kicad/boards/PWR_A/placement_study.py --check          fail unless every study reproduces
  python3 build/kicad/boards/PWR_A/placement_study.py --spec <file>    only that spec (a file name of SPECS)

SPECS: PWR_A.spec-draft.json -> placement-study.json (the pre-SHRINK draft of W2 PCB-PWRA-1/2, kept as the record of
the obstacle fix) and PWR_A.spec-shrink2.json -> placement-study-shrink2.json (generated by make_spec.py: the two-sided
SHRINK-2 PWR-A). The draft still carries the B2B2 placeholder (Hirose FX8 land of the KiCad 10.0.7 image library), so
KICAD10_FOOTPRINT_DIR must name a library holding Connector_Hirose_FX8.pretty (board_gen.image_library_dir; the
kicad/kicad:10.0.7 image has it); the file is SHA256-checked. The SHRINK-2 spec needs vendored footprints only.

Inputs: the spec (this directory), pcb/board_gen.py (its validation, net resolution, footprint geometry and
deterministic shelf packer are reused, nothing is re-implemented), the mechanical contract
(mechanical/generated/contract/boards.json PWR and PWR_B), design/E1-E5, the portable footprint manifest,
pcb/partition-spec.json, pcb/partition-budget.json, pcb/generated/netclasses.json and pcb/generated/b2b-nets.json;
for the B2B check also pcb/boards/PWR_B.json and build/kicad/boards/PWR_B/connectors.json (PWR_B, read only).

W2 PCB-PWRA-3: (1) obstacle fix: try_pack hands board_gen.place_groups the obstacle boxes of the parts already placed
({**geometry, **geo}: the obstacle geometry wins); before, their own footprint geometry won ({**geo, **geometry}), so an
obstacle was checked at the origin anchor of as_obstacles() instead of its placed box. (2) the budget candidate is the
spec's budget_candidate, else the candidates.<id> its reserved_area_mm2 source names, else the chosen one. (3) groups
with side B (two-sided SHRINK-2): packed after the top groups against the bottom parts, the side-B reserved areas
(thermal_bond zones) and the THT pin fields + tht_margin of the placed top parts; the bottom fill uses the bottom usable
area (outline - hole keepouts - thermal_bond zones - those pin fields, exact per 0.05 mm row). (4) planned_footprints:
a pending SHRINK-2 footprint swap is studied with the planned footprint's courtyard. (5) the B2B check reads a graph mate
(J209) and an explicit pin map. (6) H-TRIM: the PWR-A top parts under the PWR-B THT pin fields against zone_h_max_mm.
(7) turn_whatif: the bottom-edge need and PWR-B strip depth with the named headers turned by 90 degrees.

What it reports (MODEL / CI-free planning result, not a KiCad board, not a hardware result):
- the anchors of the spec placed by board_gen.placed_geometry and checked against the contract (Pololu pin fields
  within 0.05 mm, regulators inside thermal_bond zones 1-2, harness headers on their exit edges, outline, holes);
- every placement group packed with board_gen.place_groups in spec order, first into its region and then into its
  alt_regions; a group that fits nowhere is listed with the planner's refusal, and its refs stay unplaced;
- the courtyard fill (sum of courtyard boxes + reserved areas over the usable outline) against the fallback trigger
  0.60 of pcb/partition-spec.json (F2 for the draft, F2-C for SHRINK-2), and the free area left after the anchors;
- the exit-edge length demand of the PWR-A and PWR-B harness headers, the PWR-B cut-outs this placement needs
  (windows over PWR-A parts taller than hA, header edge strips, test-point probe windows), the THT pads inside the
  thermal_bond zones (plate pockets, M-07) and a geometric pre-check of the scripted copper;
- the B2B pair (spec b2b): every contact of the PWR_A mate against its PWR_B mate, pin for pin (nets) and in position
  (planner geometry of both lands, and the contact positions in PWR_B connectors.json from its CI route run);
- the planned origin of every placed ref (positions), the input of lab5_budget.py.
"""
