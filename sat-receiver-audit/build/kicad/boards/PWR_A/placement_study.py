def r4(v):
    return bg.r4(v)


def area(box):
    return (box[2] - box[0]) * (box[3] - box[1])


def inside(box, rect, tol=1e-6):
    return box[0] >= rect[0] - tol and box[1] >= rect[1] - tol and box[2] <= rect[2] + tol and box[3] <= rect[3] + tol


def xywh(rect):
    x, y, w, h = rect
    return [x, y, x + w, y + h]


def polygon_area(poly):
    return abs(sum(x1 * y2 - x2 * y1 for (x1, y1), (x2, y2) in zip(poly, poly[1:] + poly[:1]))) / 2


def edge_spans(contract):
    """Available edge segments per exit edge, minus the chords of the hole keepouts touching that edge."""
    out = {}
    for z in contract['edge_zones']:
        key = {'bottom': 'bottom', 'right': 'right'}.get(z['edge'])
        if z['edge'] == 'top':
            key = 'top_sl2' if 'at' in z else 'top_left'
        out[key] = {'edge': z['edge'], 'at': z.get('at'), 'span': z['span'], 'use': z['use']}
    return out


def header_extent(box, edge):
    """Length of a header courtyard along its exit edge."""
    return (box[3] - box[1]) if edge == 'right' else (box[2] - box[0])


def on_edge(box, edge, outline_box, spans):
    x0, y0, x1, y1 = outline_box
    if edge == 'bottom':
        return abs(box[1] - y0) <= EDGE_TOL
    if edge == 'right':
        return abs(box[2] - x1) <= EDGE_TOL
    if edge == 'top_left':
        return abs(box[3] - y1) <= EDGE_TOL and box[2] <= spans['top_left']['span'][1] + 1e-6
    if edge == 'top_sl2':
        lo, hi = spans['top_sl2']['span']
        return abs(box[3] - spans['top_sl2']['at']) <= EDGE_TOL and box[0] >= lo - 1e-6 and box[2] <= hi + 1e-6
    return False


def budget_candidate(spec, budget):
    """The partition-budget candidate a spec is studied against (see the module docstring, (2))."""
    if spec.get('budget_candidate'):
        return spec['budget_candidate']
    for res in spec.get('reserved_area_mm2', []):
        m = re.search(r'candidates\.([A-Za-z0-9_]+)\.', res.get('area_mm2_source', ''))
        if m:
            return m.group(1)
    return budget['chosen']


def tht_field(geo, anchor):
    """Box of the THT pads and NPTH pegs of a placed footprint (pad sizes turned with the anchor), or None."""
    pads = [p for p in geo['pads'] if p['type'] in ('thru_hole', 'np_thru_hole')]
    if not pads:
        return None
    pts = []
    turned = int(round(float(anchor.get('rotation', 0)) / 90.0)) % 2
    # every pad of the footprint goes in (an anchor may align on a pad); THT pads and NPTH pegs get keys of their own
    keyed = [{**p, 'number': f'#{i}'} for i, p in enumerate(geo['pads'])]
    where = bg.placed_geometry({'pads': keyed + [p for p in geo['pads'] if p['number']], 'courtyard': None}, anchor)['pads']
    for i, p in enumerate(geo['pads']):
        if p['type'] not in ('thru_hole', 'np_thru_hole'):
            continue
        cx, cy0 = where[f'#{i}'][0]
        w, h = (p['size'][1], p['size'][0]) if turned else (p['size'][0], p['size'][1])
        pts.append([cx, cy0, w, h])
    return [r4(min(p[0] - p[2] / 2 for p in pts)), r4(min(p[1] - p[3] / 2 for p in pts)),
            r4(max(p[0] + p[2] / 2 for p in pts)), r4(max(p[1] + p[3] / 2 for p in pts))], \
        sum(p['type'] == 'thru_hole' for p in pads), sum(p['type'] == 'np_thru_hole' for p in pads)


def free_length(intervals, cuts):
    """Length of the union of intervals minus the union of cuts (1-D, [a, b] lists)."""
    out = 0.0
    for a, b in intervals:
        segs = [[a, b]]
        for c, d in cuts:
            nxt = []
            for s, e in segs:
                if d <= s or c >= e:
                    nxt.append([s, e])
                    continue
                if c > s:
                    nxt.append([s, c])
                if d < e:
                    nxt.append([d, e])
            segs = nxt
        out += sum(e - s for s, e in segs)
    return out


def bottom_usable(outline, hole_list, boxes):
    """Area of the outline outside the hole keepout circles and outside every box (rows of ROW_STEP, exact along x)."""
    ys = [p[1] for p in outline]
    y0, y1 = min(ys), max(ys)
    n = int(round((y1 - y0) / ROW_STEP))
    total = 0.0
    for i in range(n):
        y = y0 + (i + 0.5) * ROW_STEP
        xs = []
        for (ax, ay), (bx, by) in zip(outline, outline[1:] + outline[:1]):
            if (ay <= y < by) or (by <= y < ay):
                xs.append(ax + (y - ay) * (bx - ax) / (by - ay))
        xs.sort()
        spans = [[xs[k], xs[k + 1]] for k in range(0, len(xs) - 1, 2)]
        cuts = []
        for h in hole_list:
            r = h['keepout_d'] / 2
            dy = abs(y - h['at'][1])
            if dy < r:
                c = math.sqrt(r * r - dy * dy)
                cuts.append([h['at'][0] - c, h['at'][0] + c])
        for b in boxes:
            if b[1] <= y < b[3]:
                cuts.append([b[0], b[2]])
        total += free_length(spans, cuts) * ROW_STEP
    return total


def _touch(a, b, eps=1e-6):
    return a[0] <= b[2] + eps and b[0] <= a[2] + eps and a[1] <= b[3] + eps and b[1] <= a[3] + eps


def _box_point_dist(b, x, y):
    return math.hypot(max(b[0] - x, 0, x - b[2]), max(b[1] - y, 0, y - b[3]))


def trunk_check(spec, pad_index):
    """Review fixes F1/F2 (W2 PCB-PWRA-3): the scripted copper of every net of spec power_stages.trunks joins the named pads
    by itself. Pours join when they share a layer and touch or overlap; a through via joins every pour and pad it touches;
    a pad joins a pour of its layer (THT pads every layer). Geometry of the planned pads, no KiCad fill."""
    trunks = (spec.get('power_stages') or {}).get('trunks') or {}
    pre = spec['pre_route']
    rows = []
    for net, targets in sorted(trunks.items()):
        nodes = []
        for z in pre.get('zones', []):
            if z['net'] == net and z.get('outline', 'board') != 'board':
                xs, ys = [p[0] for p in z['outline']], [p[1] for p in z['outline']]
                nodes.append(('zone', z['id'], z['layer'], [min(xs), min(ys), max(xs), max(ys)]))
        for v in pre.get('vias', []):
            if v['net'] == net:
                nodes.append(('via', v['id'], None, (v['at'][0], v['at'][1], v['diameter_mm'] / 2)))
        for p in pad_index:
            if p['net'] == net:
                nodes.append(('pad', f'{p["ref"]}.{p["pad"]}', None if p['tht'] else ('F.Cu' if p['side'] == 'F' else 'B.Cu'),
                              p['box']))
        parent = list(range(len(nodes)))

        def find(i):
            while parent[i] != i:
                parent[i] = parent[parent[i]]
                i = parent[i]
            return i
        for i, a in enumerate(nodes):
            for j in range(i + 1, len(nodes)):
                b = nodes[j]
                if a[0] == 'via' and b[0] == 'via' or a[0] == 'pad' and b[0] == 'pad':
                    continue
                if a[0] == 'via' or b[0] == 'via':
                    v, o = (a, b) if a[0] == 'via' else (b, a)
                    hit = _box_point_dist(o[3], v[3][0], v[3][1]) <= v[3][2] + 1e-9
                else:
                    hit = (a[2] is None or b[2] is None or a[2] == b[2]) and _touch(a[3], b[3])
                if hit:
                    parent[find(i)] = find(j)
        comp_of = {}
        for i, n in enumerate(nodes):
            if n[0] == 'pad':
                comp_of.setdefault(n[1], set()).add(find(i))
        copper_roots = {find(i) for i, n in enumerate(nodes) if n[0] != 'pad'}
        missing = [t for t in targets if t not in comp_of]
        roots = [sorted(comp_of[t] & copper_roots) for t in targets if t in comp_of]
        common = set.intersection(*[set(r) for r in roots]) if roots and all(roots) else set()
        unjoined = [t for t in targets if t in comp_of and not (comp_of[t] & common)]
        rows.append({'net': net, 'targets': targets, 'scripted_items': sum(1 for n in nodes if n[0] != 'pad'),
                     'targets_not_placed': missing, 'targets_not_joined': unjoined,
                     'joined': not missing and not unjoined and bool(common)})
    return {'rule': 'spec power_stages.trunks: the scripted pours and vias of each net join all its listed pads by themselves '
                    '(MODEL geometry of the planned pads, no KiCad fill)',
            'nets': rows, 'passed': all(r['joined'] for r in rows)}


CORRIDOR_STEP = 0.2       # mm raster pitch of the corridor pre-check
CORRIDOR_MARGIN = 15.0    # mm around the terminals and scripted copper of a net
CORRIDOR_CLEARANCE = 0.15  # mm, netclasses.json clearance of the power classes
CORRIDOR_DESIGN_CLASS = {'E1_CONV_IN': 'BATT'}  # no NET_CURRENT entry yet (GR5A-03): the class it is scripted at


def corridor_check(spec, pad_index, netclasses, outline, hole_list):
    """Review fix F2 (W2 PCB-PWRA-3): for every BATT/PWR3A net of PWR-A, can copper of the class width reach its
    router-left pads on the outer layers? A raster search (CORRIDOR_STEP) from the scripted copper of the net (else from
    its largest pad) over F.Cu and B.Cu, a layer change anywhere both layers are free (a router via). Obstacles: pads, scripted
    pours and vias of other nets (+ half the width + clearance), the hole keep-outs, the outline inset (edge clearance 0.3) and
    on B.Cu the GND bond copper of the thermal_bond zones; around an own pad the copper may narrow within half the width (the
    check_boards pin-entry rule). Pads listed in power_stages.branch_pads carry no power current and are not checked here.
    MODEL: planner positions, not a routed board; the router may still need other paths."""
    import collections
    cls_of = {n: v['class'] for n, v in netclasses['nets'].items()}
    width_of = {c: v.get('outer_min_width_mm') for c, v in netclasses['classes'].items()}
    branch = {n: set(v['pads']) for n, v in ((spec.get('power_stages') or {}).get('branch_pads') or {}).items()}
    pre = spec['pre_route']
    step = CORRIDOR_STEP
    xs, ys = [p[0] for p in outline], [p[1] for p in outline]
    nx, ny = int(round((max(xs) - min(xs)) / step)) + 1, int(round((max(ys) - min(ys)) / step)) + 1
    ox, oy = min(xs), min(ys)
    size = nx * ny
    edges = list(zip(outline, outline[1:] + outline[:1]))
    bonds = [z for z in spec.get('post_route_zones', []) if z['layer'] == 'B.Cu' and z['net'] == 'GND']
    base_cache = {}

    def paint(arr, box, inf, value=1):
        i0, i1 = max(0, math.ceil((box[0] - inf - ox) / step - 1e-9)), min(nx - 1, math.floor((box[2] + inf - ox) / step + 1e-9))
        j0, j1 = max(0, math.ceil((box[1] - inf - oy) / step - 1e-9)), min(ny - 1, math.floor((box[3] + inf - oy) / step + 1e-9))
        if i1 < i0 or j1 < j0:
            return
        row = bytes([value]) * (j1 - j0 + 1)
        for i in range(i0, i1 + 1):
            arr[i * ny + j0:i * ny + j1 + 1] = row

    def base(w):
        if w in base_cache:
            return base_cache[w]
        inset = 0.3 + w / 2
        layer = bytearray(size)
        for i in range(nx):
            x = ox + i * step
            for j in range(ny):
                y = oy + j * step
                if not bg.point_in_outline((x, y), outline) or any(
                        math.hypot(max(min(ax, bx) - x, 0, x - max(ax, bx)), max(min(ay, by) - y, 0, y - max(ay, by))) < inset
                        for (ax, ay), (bx, by) in edges):
                    layer[i * ny + j] = 1
        for h in hole_list:
            r = h['keepout_d'] / 2 + w / 2
            cx, cy = h['at']
            for i in range(max(0, math.ceil((cx - r - ox) / step)), min(nx - 1, math.floor((cx + r - ox) / step)) + 1):
                dx = ox + i * step - cx
                half = math.sqrt(max(r * r - dx * dx, 0.0))
                paint(layer, [ox + i * step, cy - half, ox + i * step, cy + half], 0.0)
        bot = bytearray(layer)
        for z in bonds:
            zx, zy = [p[0] for p in z['outline']], [p[1] for p in z['outline']]
            paint(bot, [min(zx), min(zy), max(zx), max(zy)], w / 2 + CORRIDOR_CLEARANCE)
        base_cache[w] = (layer, bot)
        return base_cache[w]

    layer_of = {'F.Cu': 0, 'B.Cu': 1}
    rows = []
    nets = sorted({p['net'] for p in pad_index if p['net'] and
                   (cls_of.get(p['net']) in ('BATT', 'PWR3A') or p['net'] in CORRIDOR_DESIGN_CLASS)})
    for net in nets:
        cls = cls_of.get(net) or CORRIDOR_DESIGN_CLASS[net]
        w = width_of[cls]
        inf = w / 2 + CORRIDOR_CLEARANCE
        terms = [p for p in pad_index if p['net'] == net and f'{p["ref"]}.{p["pad"]}' not in branch.get(net, set())]
        names = sorted({f'{p["ref"]}.{p["pad"]}' for p in terms}, key=lambda s: (bg.sort_ref(s.split('.')[0]), s))
        if len(names) < 2:
            continue
        own_zones = [z for z in pre.get('zones', []) if z['net'] == net and z['layer'] in layer_of]
        own_vias = [v for v in pre.get('vias', []) if v['net'] == net]
        boxes = [p['box'] for p in terms] + [[min(q[0] for q in z['outline']), min(q[1] for q in z['outline']),
                                              max(q[0] for q in z['outline']), max(q[1] for q in z['outline'])]
                                             for z in own_zones]
        win = [max(ox, min(b[0] for b in boxes) - CORRIDOR_MARGIN), max(oy, min(b[1] for b in boxes) - CORRIDOR_MARGIN),
               min(ox + (nx - 1) * step, max(b[2] for b in boxes) + CORRIDOR_MARGIN),
               min(oy + (ny - 1) * step, max(b[3] for b in boxes) + CORRIDOR_MARGIN)]
        top, bot = base(w)
        blocked = [bytearray(top), bytearray(bot)]
        for p in pad_index:
            if p['net'] == net:
                continue
            for li in ((0, 1) if p['tht'] else ((0,) if p['side'] == 'F' else (1,))):
                paint(blocked[li], p['box'], inf)
        for z in pre.get('zones', []):
            if z['net'] != net and z['layer'] in layer_of:
                zx, zy = [q[0] for q in z['outline']], [q[1] for q in z['outline']]
                paint(blocked[layer_of[z['layer']]], [min(zx), min(zy), max(zx), max(zy)], inf)
        for v in pre.get('vias', []):
            if v['net'] != net:
                x, y = v['at']
                r = v['diameter_mm'] / 2
                for li in (0, 1):
                    paint(blocked[li], [x - r, y - r, x + r, y + r], inf)
        # own copper and pads are free; around an own pad the copper may narrow (pin entry within half the width)
        foreign = [[], []]
        for p in pad_index:
            if p['net'] != net:
                for li in ((0, 1) if p['tht'] else ((0,) if p['side'] == 'F' else (1,))):
                    foreign[li].append(p['box'])
        cells = {}
        for p in terms:
            name = f'{p["ref"]}.{p["pad"]}'
            for li in ((0, 1) if p['tht'] else ((0,) if p['side'] == 'F' else (1,))):
                b = p['box']
                ent = [b[0] - w / 2, b[1] - w / 2, b[2] + w / 2, b[3] + w / 2]
                hit = [f for f in foreign[li] if _touch(f, [ent[0] - CORRIDOR_CLEARANCE, ent[1] - CORRIDOR_CLEARANCE,
                                                           ent[2] + CORRIDOR_CLEARANCE, ent[3] + CORRIDOR_CLEARANCE])]
                tmp = bytearray(size)
                paint(tmp, ent, 0.0)
                for f in hit:
                    paint(tmp, f, CORRIDOR_CLEARANCE, 0)
                i0, i1 = max(0, math.floor((ent[0] - ox) / step)), min(nx - 1, math.ceil((ent[2] - ox) / step))
                j0, j1 = max(0, math.floor((ent[1] - oy) / step)), min(ny - 1, math.ceil((ent[3] - oy) / step))
                own = set()
                for i in range(i0, i1 + 1):
                    for j in range(j0, j1 + 1):
                        k = i * ny + j
                        if tmp[k]:
                            blocked[li][k] = 0
                            x, y = ox + i * step, oy + j * step
                            if b[0] - 1e-9 <= x <= b[2] + 1e-9 and b[1] - 1e-9 <= y <= b[3] + 1e-9:
                                own.add(li * size + k)
                if not own:  # a pad smaller than the raster: its centre cell
                    k = int(round((p['at'][0] - ox) / step)) * ny + int(round((p['at'][1] - oy) / step))
                    blocked[li][k] = 0
                    own.add(li * size + k)
                cells.setdefault(name, set()).update(own)
        seed = set()
        for z in own_zones:
            zx, zy = [q[0] for q in z['outline']], [q[1] for q in z['outline']]
            li = layer_of[z['layer']]
            for i in range(max(0, math.ceil((min(zx) - ox) / step)), min(nx - 1, math.floor((max(zx) - ox) / step)) + 1):
                for j in range(max(0, math.ceil((min(zy) - oy) / step)), min(ny - 1, math.floor((max(zy) - oy) / step)) + 1):
                    blocked[li][i * ny + j] = 0
                    seed.add(li * size + i * ny + j)
        for v in own_vias:
            k = int(round((v['at'][0] - ox) / step)) * ny + int(round((v['at'][1] - oy) / step))
            for li in (0, 1):
                blocked[li][k] = 0
                seed.add(li * size + k)
        wi0, wi1 = int((win[0] - ox) / step), int(math.ceil((win[2] - ox) / step))
        wj0, wj1 = int((win[1] - oy) / step), int(math.ceil((win[3] - oy) / step))
        flat = blocked[0] + blocked[1]
        seen = bytearray(2 * size)

        def search(start):
            q = collections.deque(start)
            for s in start:
                seen[s] = 1
            while q:
                c = q.popleft()
                li, k = divmod(c, size)
                i, j = divmod(k, ny)
                for ni, nj in ((i + 1, j), (i - 1, j), (i, j + 1), (i, j - 1)):
                    if wi0 <= ni <= wi1 and wj0 <= nj <= wj1:
                        n = li * size + ni * ny + nj
                        if not seen[n] and not flat[n]:
                            seen[n] = 1
                            q.append(n)
                o = (1 - li) * size + k
                if not seen[o] and not flat[o]:
                    seen[o] = 1
                    q.append(o)
        comps = []
        start = seed or cells[max(names, key=lambda n: max(len(cells[n]), 0))]
        search(start)
        while True:
            got = [n for n in names if any(seen[c] for c in cells[n])]
            comps.append(sorted(set(got) - {x for cp in comps for x in cp}, key=names.index))
            rest = [n for n in names if not any(seen[c] for c in cells[n])]
            if not rest or len(comps) >= 8:
                if rest:
                    comps.append(rest)
                break
            search(cells[rest[0]])
        rows.append({'net': net, 'class': cls, 'width_mm': w, 'scripted_seed': bool(seed), 'terminals': len(names),
                     'branch_pads_not_checked': sorted(branch.get(net, set())),
                     'components': comps, 'connected': len(comps) == 1})
    return {'rule': 'BATT/PWR3A nets (E1_CONV_IN at BATT, the width it is scripted at): class-width corridor on F.Cu/B.Cu from '
                    'the scripted copper of the net (else its largest pad) to every other pad; components = pad sets one '
                    'corridor joins (MODEL raster, CORRIDOR_STEP mm; planner positions, not a routed board)',
            'step_mm': step, 'clearance_mm': CORRIDOR_CLEARANCE, 'nets': rows,
            'split_nets': [r['net'] for r in rows if not r['connected']],
            'all_connected': all(r['connected'] for r in rows),
            'note': 'report for W2 PCB-PWRA-4, not a gate: a split net needs a re-placement or a narrower entry there; the '
                    'scripted trunks themselves are checked by scripted_copper_precheck.trunks'}


def study(spec_name):
    spec = bg.read_json(HERE / spec_name)
    board = spec['board_id']
    bg.validate_spec(spec, board)
    contract_all = bg.read_json(CONTRACT)['boards']
    contract = contract_all[spec['contract']['board']]
    contract_b = contract_all['PWR_B']
    pspec = bg.read_json(PARTITION_SPEC)
    budget = bg.read_json(BUDGET)
    cand_id = budget_candidate(spec, budget)
    cand = budget['candidates'][cand_id]
    netclasses = bg.read_json(NETCLASSES)
    b2b_nets = bg.read_json(B2B_NETS)
    graph = bg.load_graph()
    db = bg.parts_by_ref()
    manifest = bg.read_json(bg.MANIFEST)
    fp_files = {f['footprint']: f for f in manifest['footprints']}
    project = bg.read_json(BASE / spec['project'])
    project_problems = bg.check_project(spec, project)
    template = bg.resolve(spec, graph, manifest)
    partition = bg.read_json(BASE / spec['partition'])
    domain = bg.domain_audit(spec, partition)
    geometry = {p['ref']: bg.footprint_geometry(bg.footprint_file(p).read_text(encoding='utf-8')) for p in template}
    # (4) a pending SHRINK-2 footprint swap: the planned footprint's courtyard and pads stand for the graph footprint
    planned_fp = spec.get('planned_footprints', {})
    for ref, pf in planned_fp.items():
        geometry[ref] = bg.footprint_geometry((BASE / fp_files[pf['footprint']]['file']).read_text(encoding='utf-8'))
    outline = contract['outline_mm']
    xs, ys = [p[0] for p in outline], [p[1] for p in outline]
    outline_box = [min(xs), min(ys), max(xs), max(ys)]
    hole_list = bg.holes(spec, contract)
    hA = pspec['parameters']['hA']
    margin = pspec['parameters']['window_margin']
    exit_edge = {**EXIT_EDGE, **spec.get('exit_edges', {})}
    two_sided = spec.get('two_sided')
    tht_margin = two_sided['tht_margin_mm'] if two_sided else 1.0
    bond_zones = (two_sided['thermal_bond_zones'] if two_sided else [xywh(z) for z in contract['thermal_bond_mm']])

    # --- usable area (outline minus the hole keepout circles, as pcb/partition_budget.py counts it) ---
    outline_area = polygon_area(outline)
    keepout_area = sum(math.pi * (h['keepout_d'] / 2) ** 2 for h in hole_list)
    usable = outline_area - keepout_area

    # --- anchors ---
    anchored = {p['ref']: p['anchor'] for p in template if p.get('anchor')}
    placed = {}
    anchor_rows, anchor_errors = [], []
    for ref in sorted(anchored, key=bg.sort_ref):
        g = bg.placed_geometry(geometry[ref], anchored[ref])
        placed[ref] = {'side': anchored[ref].get('side', 'F'), **g}
        box = g['box']
        row = {'ref': ref, 'at': anchored[ref]['at'], 'rotation': anchored[ref].get('rotation', 0),
               'courtyard_box': box, 'checks': {}}
        row['checks']['inside_outline'] = all(bg.point_in_outline(c, outline) for c in
                                              ((box[0], box[1]), (box[2], box[1]), (box[2], box[3]), (box[0], box[3])))
        hits = [h['ref'] for h in hole_list if bg.box_circle_distance(box, h['at']) < h['keepout_d'] / 2 - 1e-9]
        row['checks']['clear_of_hole_keepouts'] = not hits
        if ref in POLOLU and len(contract.get('modules_on_board') or []) > POLOLU[ref]:
            mod = contract['modules_on_board'][POLOLU[ref]]
            pf = mod['pin_field']
            want = [pf[0], pf[1], pf[0] + pf[2], pf[1] + pf[3]]
            fp_pads = [p for p in geometry[ref]['pads'] if p['type'] == 'thru_hole']
            boxes = []
            for p in fp_pads:
                cx, cy = bg.placed_geometry({'pads': [p], 'courtyard': None}, anchored[ref])['pads'][str(p['number'])][0]
                boxes.append([cx - p['size'][0] / 2, cy - p['size'][1] / 2, cx + p['size'][0] / 2, cy + p['size'][1] / 2])
            got = [r4(min(b[0] for b in boxes)), r4(min(b[1] for b in boxes)), r4(max(b[2] for b in boxes)),
                   r4(max(b[3] for b in boxes))]
            dev = max(abs(a - b) for a, b in zip(got, want))
            row['checks']['pin_field_contract'] = {'contract': want, 'placed_pad_box': got, 'max_dev_mm': r4(dev),
                                                   'within_0_05': dev <= PIN_FIELD_TOL + 1e-9}
        if ref in BOND_ZONE_REFS:
            zones = [i for i in BOND_ZONE_REFS[ref] if inside(box, xywh(contract['thermal_bond_mm'][i - 1]))]
            row['checks']['inside_thermal_bond_zone'] = zones or False
        if ref in exit_edge:
            row['checks']['exit_edge'] = exit_edge[ref]
        for key, val in row['checks'].items():
            bad = (val is False) or (isinstance(val, dict) and val.get('within_0_05') is False)
            if bad:
                anchor_errors.append({'ref': ref, 'check': key})
        anchor_rows.append(row)
    # (8) W2 PCB-PWRA-3 part 2: the converter-zone refs of the contract (MECH-7 converter_zone_refs) inside their
    # thermal_bond zone, and the end of the bottom-edge row against the contract row_end_max
    template_refs = {p['ref'] for p in template}
    conv_rows = []
    for zone, zrefs in sorted((contract.get('converter_zone_refs') or {}).items()):
        zrect = xywh(contract['thermal_bond_mm'][int(zone) - 1])
        for ref in zrefs:
            if ref not in template_refs:
                conv_rows.append({'zone': int(zone), 'ref': ref, 'inside': None, 'why': 'not a PWR-A ref of this spec'})
                continue
            ok = ref in placed and inside(placed[ref]['box'], zrect)
            conv_rows.append({'zone': int(zone), 'zone_rect': zrect, 'ref': ref,
                              'courtyard_box': placed[ref]['box'] if ref in placed else None, 'inside': ok})
            if not ok:
                anchor_errors.append({'ref': ref, 'check': f'converter courtyard outside thermal_bond zone {zone}'})
    row_check = None
    if spec.get('bottom_row'):
        brow = spec['bottom_row']
        ends = {r: placed[r]['box'][2] for r in brow['refs'] if r in placed}
        end = max(ends.values()) + margin
        row_check = {'rule': brow['rule'], 'refs': brow['refs'], 'turned': brow['turned'],
                     'courtyard_end_x': {r: r4(v) for r, v in ends.items()}, 'end_x_with_margin': r4(end),
                     'row_end_max': brow['row_end_max'], 'passed': end <= brow['row_end_max'] + 1e-9}
        if not row_check['passed']:
            anchor_errors.append({'ref': max(ends, key=ends.get), 'check': 'bottom row beyond row_end_max'})
    refs_sorted = sorted(anchored, key=bg.sort_ref)
    for i, a in enumerate(refs_sorted):
        for b in refs_sorted[i + 1:]:
            if placed[a]['side'] == placed[b]['side'] and bg.rects_overlap(placed[a]['box'], placed[b]['box']):
                anchor_errors.append({'ref': a, 'check': f'courtyard overlaps {b}'})

    # --- reserved areas (study obstacles: no footprint exists for them yet; side B = bottom-face keep-outs) ---
    reserved_rows = []
    obstacles = []
    for res in spec.get('reserved_areas', []):
        rect = res['rect']
        side = res.get('side', 'F')
        ok = all(bg.point_in_outline(c, outline) for c in ((rect[0], rect[1]), (rect[2], rect[1]), (rect[2], rect[3]),
                                                           (rect[0], rect[3])))
        clash = sorted(r for r, p in placed.items() if p['side'] == side and bg.rects_overlap(rect, p['box']))
        holes_hit = [h['ref'] for h in hole_list if bg.box_circle_distance(rect, h['at']) < h['keepout_d'] / 2]
        row = {'id': res['id'], 'rect': rect, 'area_mm2': r4(area(rect)), 'inside_outline': ok,
               'overlaps_anchors': clash, 'hole_keepouts_hit': holes_hit}
        if 'side' in res:
            row['side'] = side
        reserved_rows.append(row)
        obstacles.append({'ref': '__' + res['id'], 'box': rect, 'side': side, 'kind': res.get('kind')})
    reserve_mm2 = 0.0
    reserve_rows = []
    for res in spec.get('reserved_area_mm2', []):
        val = cand['pwr_a_keepouts_mm2'] if res['id'] == 'PWR_B_THT_KEEPOUTS' else 0.0
        reserve_mm2 += val
        reserve_rows.append({'id': res['id'], 'area_mm2': r4(val), 'source': res['area_mm2_source']})

    # --- chunked first-fit with the board_gen planner ---
    # Each region hosts at most one packed chunk (board_gen shelf-packs a group from the top-left corner of its
    # region, so a second group in the same rectangle would collide); the strip left below the chunk's lowest
    # shelf becomes a new region '<name>+'. For every spec group in order, the regions of its side are tried in the
    # order region_name, alt_regions, then every other free region of that side; in each, the members still unplaced
    # are added one at a time, largest courtyard first, and kept when board_gen.place_groups still packs the chunk; a
    # member is turned by 90 degrees when that aligns its long side with the region's long side. Already placed parts
    # and reserved areas of the same side are fixed obstacles; on side B also the THT pin fields of the placed top
    # parts + tht_margin (added before the first bottom group).
    regions_by_side = {'F': dict(spec['regions']['rects']), 'B': dict(spec['regions'].get('bottom_rects', {}))}
    used = {'F': set(), 'B': set()}
    chunks = []  # accepted board_gen groups
    group_rows = []

    def as_obstacles(boxes, side):
        # A fixed box as a pad-less part at the origin whose courtyard lands on the box: board_gen.placed_geometry turns
        # local (x, y) into board (x, -y) on side F and, flipped, into (-x, -y) on side B (placement probe 5 of W2
        # PCB-PWRA-3 found the side-B obstacles mirrored to negative x, off the board, before this was handled).
        anchor = {'at': [0.0, 0.0], 'align': 'origin', 'rotation': 0, 'side': side}
        parts = [{'ref': ref, 'anchor': dict(anchor)} for ref in boxes]
        if side == 'B':
            geo = {ref: {'pads': [], 'courtyard': [-b[2], -b[3], -b[0], -b[1]]} for ref, b in boxes.items()}
        else:
            geo = {ref: {'pads': [], 'courtyard': [b[0], -b[3], b[2], -b[1]]} for ref, b in boxes.items()}
        for ref, b in boxes.items():
            got = bg.placed_geometry(geo[ref], anchor)['box']
            if any(abs(u - v) > 1e-6 for u, v in zip(got, b)):
                raise SystemExit(f'placement_study: obstacle {ref} on side {side} lands at {got}, not {b}')
        return parts, geo

    fixed = {'F': {}, 'B': {}}
    for ref, p in placed.items():
        fixed[p['side']][ref] = p['box']
    for o in obstacles:
        fixed[o['side']][o['ref']] = o['box']
    tht_obstacles = {}

    def add_tht_obstacles():
        # W2 PCB-PWRA-3 part 2: a through via of the scripted copper is a bottom obstacle too (its diameter + VIA_MARGIN)
        for via in spec['pre_route'].get('vias', []):
            rv = via['diameter_mm'] / 2 + VIA_MARGIN
            x, y = via['at']
            tht_obstacles['__VIA_' + via['id']] = [r4(x - rv), r4(y - rv), r4(x + rv), r4(y + rv)]
        for ref in sorted(placed, key=bg.sort_ref):
            if placed[ref]['side'] != 'F':
                continue
            anchor = anchored.get(ref) or group_anchor_of[ref]
            f = tht_field(geometry[ref], anchor)
            if f:
                b = f[0]
                tht_obstacles['__THT_' + ref] = [r4(b[0] - tht_margin), r4(b[1] - tht_margin), r4(b[2] + tht_margin),
                                                 r4(b[3] + tht_margin)]
        fixed['B'].update(tht_obstacles)

    def orient(ref, region):
        b = geometry[ref]['courtyard']
        w, h = b[2] - b[0], b[3] - b[1]
        rw, rh = region[2] - region[0], region[3] - region[1]
        rot = 0 if (w >= h) == (rw >= rh) else 90
        if rot == 0 and (w > rw or h > rh) and h <= rw and w <= rh:
            rot = 90
        if rot == 90 and (h > rw or w > rh) and w <= rw and h <= rh:
            rot = 0
        return rot

    def try_pack(gid, region, members, side):
        parts, geo = as_obstacles(fixed[side], side)
        trial = {'groups': [{'id': gid, 'region': region, 'side': side, 'gap_mm': 0.5, 'members': members}]}
        try:
            # (1) the obstacle boxes win over the footprint geometry of the same refs
            anchors, rows = bg.place_groups(trial, parts + [t for t in template if t['ref'] in {m['ref'] for m in members}],
                                            {**geometry, **geo}, hole_list, outline)
        except SystemExit as error:  # SpecError / PackError
            return None, str(error).replace('board_gen: ', '')
        return (anchors, rows), None

    group_anchor_of = {}
    for group in spec['groups']:
        side = group.get('side', 'F')
        if side == 'B' and not tht_obstacles:
            add_tht_obstacles()
        regions = regions_by_side[side]
        members = [m['ref'] for m in group['members']]
        demand = sum(area(geometry[m]['courtyard']) for m in members)
        order = [group['region_name']] + list(group.get('alt_regions', [])) + [n for n in regions]
        seen, tried, used_here, remaining = set(), [], [], list(members)
        i = 0
        while i < len(order) and remaining:
            name = order[i]
            i += 1
            if name in seen or name in used[side] or name not in regions:
                continue
            seen.add(name)
            region = regions[name]
            cand_refs = sorted(remaining, key=lambda r: (-round(area(geometry[r]['courtyard']), 6), bg.sort_ref(r)))
            chunk, last = [], None
            for ref in cand_refs:
                member = {'ref': ref, 'rotation': orient(ref, region)}
                ok, why = try_pack(f'{group["id"]}@{name}', region, chunk + [member], side)
                if ok:
                    chunk.append(member)
                    last = ok
                elif not chunk:
                    tried.append({'region': name, 'first_refusal': why})
            if not chunk:
                continue
            anchors_c, rows_c = last
            gid = f'{group["id"]}@{name}'
            chunks.append({'id': gid, 'region': region, 'side': side, 'gap_mm': 0.5, 'members': chunk})
            used[side].add(name)
            for row in rows_c:
                g = bg.placed_geometry(geometry[row['ref']], anchors_c[row['ref']])
                placed[row['ref']] = {'side': side, **g}
                fixed[side][row['ref']] = g['box']
                group_anchor_of[row['ref']] = anchors_c[row['ref']]
            placed_here = [m['ref'] for m in chunk]
            remaining = [r for r in remaining if r not in placed_here]
            low = min(placed[r]['box'][1] for r in placed_here)
            if low - 0.5 - region[1] >= 1.5:
                regions[name + '+'] = [region[0], region[1], region[2], r4(low - 0.5)]
                order.insert(i, name + '+')
            # W2 PCB-PWRA-3 part 2: the strip right of the chunk is free too (no chunk part lies right of its widest
            # shelf); the long thin plate pockets PB* need it (a chunk otherwise takes a whole 40 x 6 mm pocket)
            right = max(placed[r]['box'][2] for r in placed_here)
            if region[2] - (right + 0.5) >= 1.5:
                regions[name + '>'] = [r4(right + 0.5), region[1], region[2], region[3]]
                order.insert(i, name + '>')
            used_here.append({'region': name, 'refs': len(placed_here),
                              'courtyard_mm2': r4(sum(area(geometry[r]['courtyard']) for r in placed_here)),
                              'region_mm2': r4(area(region))})
        row = {'group': group['id'], 'members': len(members), 'courtyard_mm2': r4(demand),
               'placed_refs': len(members) - len(remaining), 'chunks': used_here,
               'unplaced_refs': sorted(remaining, key=bg.sort_ref), 'regions_refused': tried}
        if side != 'F':
            row['side'] = side
        group_rows.append(row)
    if any(g.get('side', 'F') == 'B' for g in spec['groups']) and not tht_obstacles:
        add_tht_obstacles()
    # The accepted chunks, re-run once together through board_gen.place_groups, give the plan of record.
    anchor_parts = [p for p in template if p.get('anchor')]
    res_parts, res_geo = [], {}
    for side in ('F', 'B'):
        boxes = {o['ref']: o['box'] for o in obstacles if o['side'] == side}
        if side == 'B':
            boxes.update(tht_obstacles)
        p_, g_ = as_obstacles(boxes, side)
        res_parts += p_
        res_geo.update(g_)
    group_anchors, plan_rows = (bg.place_groups({'groups': chunks}, anchor_parts + res_parts + [
        t for t in template if not t.get('anchor')], {**geometry, **res_geo}, hole_list, outline) if chunks else ({}, []))
    for row in plan_rows:
        g = bg.placed_geometry(geometry[row['ref']], group_anchors[row['ref']])
        if g['box'] != placed[row['ref']]['box']:
            raise SystemExit(f'placement_study: the joint re-run moved {row["ref"]}')
    # Independent overlap check of the plan of record (board boxes, not the planner's obstacle parts): per side, every
    # placed courtyard against every other one and against the reserved areas of that side; on side B also against the
    # THT pin fields of the top parts + tht_margin. Anchor-anchor overlaps are reported under anchors.errors.
    overlap_rows = []
    for side in ('F', 'B'):
        items = [(ref, p['box']) for ref, p in sorted(placed.items()) if p['side'] == side and p['box']]
        fixed_items = [(o['ref'][2:], o['box']) for o in obstacles if o['side'] == side]
        if side == 'B':
            fixed_items += [(k[2:], b) for k, b in sorted(tht_obstacles.items())]
        for i, (a, ba) in enumerate(items):
            for b, bb in items[i + 1:]:
                if bg.rects_overlap(ba, bb) and not (a in anchored and b in anchored):
                    overlap_rows.append({'side': side, 'a': a, 'b': b})
            for b, bb in fixed_items:
                # an anchored power-stage part sits on its scripted pour by design (copper keep-outs CU_* hold the planner off)
                if b.startswith('CU_') and a in anchored:
                    continue
                if bg.rects_overlap(ba, bb) and not (b.startswith('THT_') and b[4:] == a):
                    overlap_rows.append({'side': side, 'a': a, 'b': b})

    # --- fill ---
    all_refs = [p['ref'] for p in template]
    bottom_refs = sorted({m['ref'] for g in spec['groups'] if g.get('side', 'F') == 'B' for m in g['members']} |
                         {r for r, a in anchored.items() if a.get('side', 'F') == 'B'}, key=bg.sort_ref)
    top_refs = [r for r in all_refs if r not in set(bottom_refs)]
